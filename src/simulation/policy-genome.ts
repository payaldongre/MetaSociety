function resourceBandFor(budgetInr: number): ResourceBand {
  const share = budgetInr / REFERENCE_BUDGET;
  return share < 0.25 ? "low" : share < 0.6 ? "medium" : "high";
}

/**
 * Scale band of the policy, from the deciding authority's level and the budget.
 * A local body spending the reference envelope stays "local"; a state-level
 * authority is at least "state".
 */
function scaleFor(authorityLevel: GovernanceLevel, budgetInr: number): GenomeScale {
  const order: GovernanceLevel[] = ["local", "district", "state", "national"];
  const base = order.indexOf(authorityLevel);
  const budgetLift = budgetInr >= REFERENCE_BUDGET ? 1 : 0;
  const idx = Math.min(order.length - 1, base + budgetLift);
  return (["local", "district", "state", "national"] as GenomeScale[])[idx];
}

/* ------------------------------------------------------------------ */
/* Derivation                                                          */
/* ------------------------------------------------------------------ */

/**
 * Derive the genome of a proposed policy. Pure and deterministic: the same
 * policy and brief always produce the same genome.
 */
export function genomeFromPolicy(policy: PolicyVector, brief?: PolicyBrief): PolicyGenome {
  const channels = selectedChannels(policy.channelIds);
  const profiles = channels.map((c) => CHANNEL_GENOME_PROFILE[c.id]).filter(Boolean);

  const mechanismTags = unique(profiles.flatMap((p) => p.mechanismTags));
  const targetTraits = unique(profiles.flatMap((p) => p.targetTraits));
  const delivery = unique(profiles.flatMap((p) => p.delivery));
  const mechanisms = unique(profiles.map((p) => p.mechanism));

  const hasSeasonal = profiles.some((p) => p.seasonality === "seasonal");
  const contexts = new Set(profiles.map((p) => p.context));
  const context: GenomeContext =
    contexts.size === 1 ? [...contexts][0] : contexts.size === 0 ? "urban" : "mixed";

  const authorityLevel: GovernanceLevel = brief
    ? GOVERNANCE_REGISTRY[brief.governance.primaryDecisionAuthority]?.level ?? "local"
    : "local";

  const bnNodes = unique(channels.flatMap((c) => c.bnNodes));
  const directTargets = unique(channels.flatMap((c) => c.directTargets));

  return {
    name: policy.name,
    channelIds: [...policy.channelIds],
    domains: brief ? brief.domains : channelDomainsFor(policy.channelIds),
    mechanism: mechanisms.join(" ").trim() || "No modelled mechanism (no implemented channel selected).",
    mechanismTags,
    targetPopulation: brief?.target.description ?? "Not specified",
    targetTraits,
    context,
    seasonality: hasSeasonal ? "seasonal" : "none",
    authorityLevel,
    scale: scaleFor(authorityLevel, policy.budget),
    budgetInr: policy.budget,
    resourceBand: resourceBandFor(policy.budget),
    durationMonths: policy.durationMonths,
    intensity: policy.intensity,
    delivery,
    bnNodes,
    directTargets,
    evidenceQuality: "uncalibrated",
    provenance: [
      `mechanism tagged from channel dictionary: ${policy.channelIds.join(", ") || "none"}`,
      `context derived from channel profiles: ${context}`,
      `scale derived from deciding authority (${authorityLevel}) and budget band (${resourceBandFor(policy.budget)})`,
      brief ? "target population read from the policy brief" : "no brief supplied; target unspecified",
    ],
  };
}

function unique<T>(items: T[]): T[] {
  return [...new Set(items)];
}

/** True when a channel's genome profile exists (i.e. the channel is wired). */
export function hasGenomeProfile(channelId: string): boolean {
  return Boolean(CHANNEL_GENOME_PROFILE[channelId]) && Boolean(CHANNELS[channelId]);
}
