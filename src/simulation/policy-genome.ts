/**
 * Policy genome — the structured, historically-meaningful description of a
 * proposed policy that GGG matches against real historical predecessors.
 *
 * WHY A GENOME AND NOT THE POLICY VECTOR. The engine's `PolicyVector` is a small
 * real-valued tuple (intensity, budget, duration, allocation, channels). That is
 * enough to RUN a policy but not enough to say WHAT it is: its mechanism, target
 * population, context, delivery route, resource scale and causal pathway. Those
 * qualitative characteristics are the inherited information GGG transfers, and
 * they are what makes a housing policy structurally different from an
 * employment policy even when both are "government programmes".
 *
 * The genome contains no invented numbers. Its numeric fields (budget, duration)
 * are read from the policy; its qualitative fields are derived deterministically
 * from the channel dictionary and the brief. Nothing here is generated by a
 * language model.
 */

import { CHANNELS } from "./channel-dictionary";
import { selectedChannels } from "./instruments";
import { channelDomainsFor, type PolicyBrief } from "./policy-brief";
import { REFERENCE_BUDGET } from "./simulate";
import { GOVERNANCE_REGISTRY, type GovernanceLevel } from "./governance";
import type { EvidenceStrength } from "./evidence";
import type { MetricKey, PolicyVector } from "./types";

/* ------------------------------------------------------------------ */
/* Shape                                                               */
/* ------------------------------------------------------------------ */

export type GenomeContext = "urban" | "rural" | "mixed";
export type GenomeSeasonality = "none" | "seasonal";
export type GenomeScale = "local" | "district" | "state" | "national";

/** A resource-intensity band derived from the policy's own budget. */
export type ResourceBand = "low" | "medium" | "high";

export interface PolicyGenome {
  name: string;
  channelIds: string[];
  domains: string[];

  /** The causal mechanism the policy participates in, in words. */
  mechanism: string;
  /** Fine-grained mechanism tags used by similarity scoring. */
  mechanismTags: string[];

  targetPopulation: string;
  targetTraits: string[];

  context: GenomeContext;
  seasonality: GenomeSeasonality;

  /** The administrative level the policy is decided at. */
  authorityLevel: GovernanceLevel;
  /** Resource scale of the policy, from its budget and authority. */
  scale: GenomeScale;

  budgetInr: number;
  resourceBand: ResourceBand;
  durationMonths: number;
  intensity: number;

  /** Delivery / implementation tags. */
  delivery: string[];

  /** Bayesian-network nodes the policy's channels may move. */
  bnNodes: string[];
  /** Metrics the policy's channels declare as direct targets. */
  directTargets: MetricKey[];

  /**
   * How strong the DIRECTION evidence for this genome's mechanism is. Supplied
   * by GGG after matching; "uncalibrated" until then.
   */
  evidenceQuality: EvidenceStrength;

  /** Human-readable provenance of every derived field. */
  provenance: string[];
}

